def stage_of(char: Character, aff: int):
    """호감도 → (이름, 태도 지침, 단계 인덱스)"""
    idx = 0
    for i, (lo, _, _) in enumerate(char.stages):
        if aff >= lo:
            idx = i
    _, name, guide = char.stages[idx]
    return name, guide, idx
